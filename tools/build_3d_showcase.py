def find_source(name: str) -> pathlib.Path:
    hits = sorted(S.rglob(name))
    if not hits:
        sys.exit(f"missing acquired source {name!r}; run the panel's acquire_sources.py first")
    return hits[0]


def rows(path: pathlib.Path) -> list[dict]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def case_passed(execution_dir: str, needle: str) -> bool | None:
    status = R / execution_dir / "EXECUTION_STATUS.json"
    if not status.exists():
        return None
    for case in json.loads(status.read_text()).get("cases", []):
        if needle in case.get("record_id", ""):
            return case.get("passed")
    return None


def ca_coords(text: str, fmt: str) -> dict[str, tuple[float, float, float]]:
    """chain:resi -> CA position, from PDB or the mmCIF _atom_site loop (auth numbering)."""
    out: dict[str, tuple[float, float, float]] = {}
    if fmt == "pdb":
        for line in text.splitlines():
            if line.startswith("ATOM") and line[12:16].strip() == "CA":
                out.setdefault(f"{line[21]}:{line[22:26].strip()}",
                               (float(line[30:38]), float(line[38:46]), float(line[46:54])))
        return out
    fields, rows_, in_loop = [], [], False
    for line in text.splitlines():
        if line.startswith("_atom_site."):
            fields.append(line.split(".", 1)[1].strip()); in_loop = True; continue
        if in_loop:
            if not line.strip() or line.startswith(("#", "loop_", "_")):
                if rows_: break
                continue
            rows_.append(line.split())
    ix = {f: i for i, f in enumerate(fields)}
    for r in rows_:
        if len(r) < len(fields) or r[ix["label_atom_id"]] != "CA" or r[ix["group_PDB"]] != "ATOM":
            continue
        key = f"{r[ix.get('auth_asym_id', ix['label_asym_id'])]}:{r[ix.get('auth_seq_id', ix['label_seq_id'])]}"
        out.setdefault(key, (float(r[ix["Cartn_x"]]), float(r[ix["Cartn_y"]]), float(r[ix["Cartn_z"]])))
    return out


def one(path_glob: str) -> pathlib.Path:
    hits = sorted(R.glob(path_glob))
    if not hits:
        sys.exit(f"missing result {path_glob}")
    return hits[0]


# ------------------------------------------------------------------- commands
# The commands shown on the page are generated by the qualification executor's own
# command builders -- the same code that produced every result on the page -- so
# they cannot drift from what actually ran.
_spec = importlib.util.spec_from_file_location("qualification_execution", Q / "run_execution.py")
_EXEC = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_EXEC)
_RECORDS: dict[str, dict] = {}


def _index_records(node) -> None:
    if isinstance(node, dict):
        if "record_id" in node and "expected_result" in node:
            _RECORDS[node["record_id"]] = node
        for v in node.values():
            _index_records(v)
    elif isinstance(node, list):
        for v in node:
            _index_records(v)


_index_records(json.loads((Q / "PANEL_MANIFEST.json").read_text()))


def _portable(argv: list[str]) -> str:
    """Render argv relative to the panel directory. Refuse any absolute path."""
    base = str(Q.resolve()) + os.sep
    out = []
    for token in argv:
        token = str(token).replace(base, "")
        if token.startswith(("/", "~")) or str(pathlib.Path.home()) in token:
            sys.exit(f"refusing to publish an absolute path in a command: {token}")
        out.append(shlex.quote(token))
    return " ".join(out)


def commands_for(record_id: str, workflow: str, out_name: str) -> list[str]:
    inv = dict(_RECORDS[record_id]["expected_result"]["invocation"])
    lines = []
    upstream = inv.pop("upstream", None)
    if upstream:
        up_wf = upstream.get("workflow", "structure_qc")
        eng = _EXEC.ENGINES[up_wf]
        lines.append(_portable(eng["build_cmd"](upstream, eng["cli"], pathlib.Path("qc"))))
        inv["manifest"] = f"qc/{eng['evidence']}"
    eng = _EXEC.ENGINES[workflow]
    lines.append(_portable(eng["build_cmd"](inv, eng["cli"], pathlib.Path(out_name))))
    return lines


