#!/usr/bin/env python3
"""Build a 3D showcase of what each workbench tool does, on real public proteins.

Measurement colors come from real runs; identity colors distinguish proteins. Each panel
pairs one public PDB or AlphaFold entry from qualification panel v2 with the
per-residue output its tool actually wrote during that panel's execution, and
states that case's recorded gate result. Nothing private is read: the inputs are
public entries acquired under the panel's SOURCE_LOCK and the outputs are the
committed execution evidence.

SF-CSA instead displays two pairs of checksum-verified predicted models and
comparison values from the frozen panel manifest, with primary literature
annotations kept separate. It makes no new execution or gate-pass claim.

The state panel also derives a new pairwise alignment, per-residue displacement
and endpoint angles from the locked ABL coordinates and residue maps. These
teaching measurements are distinct from the recorded classification results.

The result is one self-contained HTML file -- 3Dmol.js (BSD-3, notice included)
and every structure are embedded -- so it opens offline and loads nothing from
the network. It is written under build/, which is gitignored: building it does
not publish it.

Requires the panel's sources to have been acquired (acquire_sources.py), NumPy
and Biopython for endpoint geometry; the built page itself needs nothing.

Usage:  python tools/build_3d_showcase.py [--out build/showcase-3d/index.html]
"""
