def sfcsa() -> dict:
    cases = json.loads((ROOT / "yauvi-structural-workbench/docs/SF_CSA_SHOWCASE_CASES.json").read_text())
    viewers, reported, studies = [], [], []
    for case in cases["cases"]:
        record = _RECORDS[case["record_id"]]
        expected = record["expected_result"]
        pair = record["pair"]
        for side, artifact, checksum, color in (
            ("query", "artifact", "checksum", "#2A9D8F"),
            ("target", "target_artifact", "target_checksum", "#E76F51"),
        ):
            source = Q / record[artifact]
            payload = source.read_bytes()
            if hashlib.sha256(payload).hexdigest() != record[checksum]:
                raise ValueError(f"SF-CSA showcase source checksum mismatch: {record[artifact]}")
            viewers.append({"label": f"{case[side].split(' (')[0]} · {pair[side + '_accession']} · AlphaFold",
                            "fmt": "pdb", "structure": payload.decode(), "cmap": {}, "uniform": color, "zoom": 0.65})
        leg = expected["structural_leg"]
        reported.append(f"{case['short_name']}: recorded aligned TM-score {float(leg['aligned_tm_score']):.4f}; "
                        f"query/target coverage {float(leg['query_coverage']):.1%}/{float(leg['target_coverage']):.1%}; "
                        f"RMSD {float(leg['rmsd']):.3f} Å. Label: {expected['judgment']['function_classification']}.")
        seq = expected["sequence_leg"]
        reported.append(f"{case['short_name']} sequence leg: " + (
            "no retained pairwise sequence comparison; absence of a row is not absence of homology."
            if "sequence_comparison" in expected["missing_evidence"] else
            f"{seq['percent_identity']}% identity; {seq['query_coverage_hsp']}% query HSP coverage; "
            f"{seq['orthology_status']} (not reciprocal-best-hit support)."))
        studies.append(case)
    return {
        "id": "sfcsa", "tool": "sf-csa", "title": "Cross-proteome comparison",
        "question": "When does a similar fold support a similar function across species?",
        "protein": "Two case studies · two fold spaces · four public protein models",
        "entry": "qualification v2, frozen comparison records",
        "link": "", "viewers": viewers,
        "legend": [("#2A9D8F", "query identity"), ("#E76F51", "comparison identity")],
        "studies": studies, "functional_analogy": cases["functional_analogy"],
        "reported": reported,
        "passed": None,
        "badge_text": "Frozen comparison; no fresh execution check",
        "view_note": "Each row is one fold family: ferredoxin-like above, OB-fold below. These are predicted monomers, independently centered, not an aligned overlay. Colors identify proteins.",
        "command_note": "Reproduction command generated from the qualification executor. Requires locked sources, Foldseek and DIAMOND. Replace the output directory with a fresh path outside the publication/source tree. The values above are frozen records, not a new run.",
        "scope": "Values read from PANEL_MANIFEST.json expected_result records; this showcase build does not rerun SF-CSA or verify current CI. Models are checksum-checked and independently centered, not superposed. Colors identify proteins, not function or confidence.",
        "limit": "These are homologous-family comparisons, not proof of convergent evolution or interchangeable function. The panel's no-false-promotion bound is definitional (Finding 7); neither pair establishes probable_same_function through reciprocal-best-hit evidence.",
        "commands": commands_for(next(r for r, v in _RECORDS.items() if "queries" in v["expected_result"].get("invocation", {})), "sf_csa", "release"),
    }


