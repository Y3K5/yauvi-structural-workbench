def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ROOT / "build" / "showcase-3d" / "index.html"))
    parser.add_argument("--workbench", action="store_true",
                        help="also write a CSP-safe copy to <out dir>/workbench/ for YAUVI_SHOWCASE_DIR")
    args = parser.parse_args()
    panels = [structqc(), membrane(), state(), site(), assembly(), sfcsa()]
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(panels))
    motion = next(p["motion"] for p in panels if "motion" in p)
    (out.parent / "ABL-endpoint-geometry.json").write_text(json.dumps(motion, indent=2) + "\n")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB, {len(panels)} panels)")
    if args.workbench:
        wb = out.parent / "workbench"
        wb.mkdir(exist_ok=True)
        (wb / "index.html").write_text(render(panels, workbench=True))
        (wb / "showcase.js").write_text(APP_JS)
        print(f"wrote {wb}/ -- launch with YAUVI_SHOWCASE_DIR={wb}")
    for p in panels:
        print(f"  {p['id']:9} passed={p['passed']}  viewers={len(p['viewers'])}")
    return 0


