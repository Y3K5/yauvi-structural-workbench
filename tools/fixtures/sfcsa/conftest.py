"""Bring the generated inputs into existence before this suite collects.

`inputs/` is generated by `build_inputs.py`, not committed -- the manifests
carry SHA-256 checksums of files the generator writes, so committing them would
mean committing two things that have to agree. The cost is that a fresh
checkout, or a tree that has just been cleaned, has no inputs, and twelve of the
tests here fail for a reason that has nothing to do with what they test.

This runs at collection time, once, and does nothing if the inputs are already
present. Drift detection stays with `build_inputs.py --check`, which is itself
one of the tests.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent

_spec = importlib.util.spec_from_file_location(
    "_sfcsa_build_inputs", HERE / "build_inputs.py"
)
_module = importlib.util.module_from_spec(_spec)
assert _spec.loader is not None
_spec.loader.exec_module(_module)
_module.ensure_inputs()
