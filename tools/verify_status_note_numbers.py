#!/usr/bin/env python3
"""Compare the prose in RELEASE_STATUS.json against the generated evidence.

`verify_release_status_digests.py` answers "is each recorded digest the digest of
its file". This answers a different question that the digest check cannot reach:
**does the sentence beside those digests quote the numbers the evidence holds?**

A digest can be perfectly current beside prose that is two collections stale, and
on 2026-09-03 it was. `scientific_execution_note` said membrane was 14/16 while
`EXECUTION_SUMMARY.json` had recorded 5/16 since collection 2.3 added the OPM
accuracy gate on 2026-08-31, and `external_benchmarks.membrane_orientation` in
the same file carried the correct 5_of_16 the whole time. The file disagreed with
itself for two collection versions and nothing could say so.

Checked here:

1.  every `<panel> N/M` claim in `scientific_execution_note`
2.  the `N of M required cases` total in that note
3.  the `beta_barrel_executes_at_N_of_16` claim in
    `external_benchmarks.membrane_orientation`

against `benchmarks/qualification-v2/results/EXECUTION_SUMMARY.json`, which is
generated by `summarize_execution.py` from the per-panel execution documents.

This is a consistency check, not a scientific one. It cannot tell you the
evidence is right; only that the prose and the evidence say the same thing.

Usage:  python tools/verify_status_note_numbers.py [--show]
Exit:   0 prose and evidence agree, 1 they do not or a file is missing.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WB = ROOT / "yauvi-structural-workbench"
STATUS = WB / "RELEASE_STATUS.json"
SUMMARY = WB / "benchmarks" / "qualification-v2" / "results" / "EXECUTION_SUMMARY.json"

# How each panel is named in the prose. The workflow id is what the evidence uses.
PROSE_NAME = {
    "structqc": "structure_qc",
    "site-context": "functional_site_state",
    "assembly-context": "assembly_interface",
    "membrane": "membrane_orientation",
    "state-atlas": "conformational_state",
}


def panel_counts(summary: dict) -> dict[str, tuple[int, int]]:
    """workflow -> (passed, total) straight from the generated summary."""
    return {p["workflow"]: (p["cases"]["passed"], p["cases"]["total"]) for p in summary["panels"]}


def check(note: str, external: str, summary: dict) -> list[str]:
    counts = panel_counts(summary)
    problems: list[str] = []
    seen: set[str] = set()

    for name, workflow in PROSE_NAME.items():
        # e.g. "StructQC 16/16", "membrane 5/16 of the adopted ..."
        m = re.search(rf"{re.escape(name)}\s+(\d+)\s*/\s*(\d+)", note, re.IGNORECASE)
        if m is None:
            continue
        seen.add(workflow)
        claimed = (int(m.group(1)), int(m.group(2)))
        actual = counts.get(workflow)
        if actual is None:
            problems.append(f"{name}: prose claims {claimed[0]}/{claimed[1]} but the summary "
                            f"records no {workflow} panel")
        elif claimed != actual:
            problems.append(f"{name}: prose claims {claimed[0]}/{claimed[1]}, "
                            f"evidence records {actual[0]}/{actual[1]}")

    missing = [w for w in counts if w not in seen]
    if missing:
        problems.append("scientific_execution_note quotes no figure for: " + ", ".join(sorted(missing)))

    m = re.search(r"(\d+)\s+of\s+(\d+)\s+required cases", note, re.IGNORECASE)
    if m is None:
        problems.append("scientific_execution_note states no 'N of M required cases' total")
    else:
        claimed = (int(m.group(1)), int(m.group(2)))
        actual = (summary["cases_passed"], summary["cases_required"])
        if claimed != actual:
            problems.append(f"total: prose claims {claimed[0]} of {claimed[1]}, "
                            f"evidence records {actual[0]} of {actual[1]}")

    m = re.search(r"executes_at_(\d+)_of_(\d+)", external)
    if m is None:
        problems.append("external_benchmarks.membrane_orientation states no executes_at_N_of_M")
    else:
        claimed = (int(m.group(1)), int(m.group(2)))
        actual = counts.get("membrane_orientation")
        if actual and claimed != actual:
            problems.append(f"external_benchmarks.membrane_orientation claims "
                            f"{claimed[0]}_of_{claimed[1]}, evidence records {actual[0]}/{actual[1]}")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--show", action="store_true", help="print the figures the evidence holds")
    args = ap.parse_args(argv)

    for path in (STATUS, SUMMARY):
        if not path.is_file():
            print(f"missing: {path.relative_to(ROOT)}", file=sys.stderr)
            return 1

    status = json.loads(STATUS.read_text(encoding="utf-8"))
    summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    note = status["qualification_evidence"]["current_v2"]["scientific_execution_note"]
    external = status["external_benchmarks"]["membrane_orientation"]

    if args.show:
        for workflow, (passed, total) in sorted(panel_counts(summary).items()):
            print(f"  {workflow:<24} {passed}/{total}")
        print(f"  {'TOTAL':<24} {summary['cases_passed']}/{summary['cases_required']}")

    problems = check(note, external, summary)
    if problems:
        for p in problems:
            print(f"MISMATCH {p}")
        return 1
    print("status prose matches the executed evidence")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
